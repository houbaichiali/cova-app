-- Native lessons become ordered SECTIONS: each section has its own title
-- (independent from the rich content, nullable) and its own rich content.
-- The right-side reading navigation is generated from the section titles only.

create table if not exists public.lesson_sections (
  id         uuid primary key, -- generated by the editor so anchors stay stable
  lesson_id  text not null,    -- text on purpose: lessons.id is text in deployments
  title      text,
  content_html text not null default '',
  position   integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists lesson_sections_lesson_idx
  on public.lesson_sections (lesson_id, position);

alter table public.lesson_sections enable row level security;
grant select on public.lesson_sections to authenticated;

do $$
begin
  if to_regclass('public.lesson_sections') is not null then
    drop policy if exists "Authenticated read lesson sections" on public.lesson_sections;
    create policy "Authenticated read lesson sections"
      on public.lesson_sections for select to authenticated
      using (true);

    drop policy if exists "Course owners manage lesson sections" on public.lesson_sections;
    create policy "Course owners manage lesson sections"
      on public.lesson_sections for all to authenticated
      using (
        exists (
          select 1 from public.lessons l join public.courses c on c.id = l.course_id
          where l.id::text = lesson_sections.lesson_id and c.created_by = (select auth.uid())
        )
      )
      with check (
        exists (
          select 1 from public.lessons l join public.courses c on c.id = l.course_id
          where l.id::text = lesson_sections.lesson_id and c.created_by = (select auth.uid())
        )
      );
  end if;
end $$;

------------------------------------------------- migrate existing lesson content

-- Old flat content_blocks (and bare text content) become sections: a heading
-- block opens a TITLED section, every other block becomes an untitled section
-- with the same rendered content. Nothing is deleted; content_blocks stays.
do $$
declare
  l record;
  b jsonb;
  r jsonb;
  section_title text;
  section_html text;
  has_content boolean;
  pos integer;
  cell text;
begin
  if to_regclass('public.lesson_sections') is null or to_regclass('public.lessons') is null then
    return;
  end if;
  if exists (select 1 from public.lesson_sections limit 1) then
    return; -- already migrated
  end if;

  for l in select id, content_blocks, content from public.lessons loop
    pos := 0;
    for b in select * from jsonb_array_elements(coalesce(l.content_blocks, '[]'::jsonb)) loop
      section_title := null;
      section_html := '';
      has_content := false;

      if b->>'type' in ('h1', 'h2', 'h3') then
        -- A heading block becomes the title of its own section.
        section_title := btrim(regexp_replace(coalesce(b->>'html', ''), '<[^>]*>', '', 'g'));
        has_content := coalesce(section_title, '') <> '';
      elsif b->>'type' = 'table' then
        section_html := '<table class="cova-table">';
        if jsonb_typeof(b->'rows') = 'array' and jsonb_array_length(b->'rows') > 0 then
          section_html := section_html || '<thead><tr>';
          for cell in select jsonb_array_elements_text(b->'rows'->0) loop
            section_html := section_html || '<th>' || cell || '</th>';
          end loop;
          section_html := section_html || '</tr></thead>';
          if jsonb_array_length(b->'rows') > 1 then
            section_html := section_html || '<tbody>';
            for r in select jsonb_array_elements(b->'rows') offset 1 loop
              section_html := section_html || '<tr>';
              for cell in select jsonb_array_elements_text(r) loop
                section_html := section_html || '<td>' || cell || '</td>';
              end loop;
              section_html := section_html || '</tr>';
            end loop;
            section_html := section_html || '</tbody>';
          end if;
        end if;
        section_html := section_html || '</table>';
        has_content := true;
      else
        section_html := coalesce(b->>'html', '');
        has_content := btrim(regexp_replace(section_html, '<[^>]*>', '', 'g')) <> '';
      end if;

      if has_content then
        insert into public.lesson_sections (id, lesson_id, title, content_html, position)
        values (gen_random_uuid(), l.id, nullif(section_title, ''), section_html, pos);
        pos := pos + 1;
      end if;
    end loop;

    -- Legacy bare-text lessons with no blocks.
    if pos = 0 and coalesce(l.content, '') <> '' then
      insert into public.lesson_sections (id, lesson_id, title, content_html, position)
      values (gen_random_uuid(), l.id, null, l.content, 0);
    end if;
  end loop;
end $$;
