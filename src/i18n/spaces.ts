const catalogs: Record<Locale, Record<SKey, string>> = { en, fr, ar };

export type ST = (key: SKey, vars?: Record<string, string | number>) => string;

export function useS(): ST {
  const { locale } = useI18n();
  return (key, vars) => {
    const tpl = catalogs[locale][key] ?? en[key];
    return vars
      ? tpl.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
      : tpl;
  };
}
